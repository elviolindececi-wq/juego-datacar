import assert from 'node:assert/strict';
import { DEALERSHIP_VEHICLES } from '../src/data/presetVehicles.ts';
import { InteractiveRacePhysics, PHYSICS_STEP } from '../src/utils/interactiveRacePhysics.ts';
const corolla=DEALERSHIP_VEHICLES.find(v=>v.id==='toyota-corolla-cross-seg-2027');
assert.ok(corolla,'Corolla no encontrado');
assert.equal(corolla.powerHp,171);
assert.equal(corolla.torqueNm,203);
assert.equal(corolla.dimensions.lengthMm,4460);
assert.ok(corolla.estimatedSimulationParameters,'No se señalaron los valores estimados');
const rivals=DEALERSHIP_VEHICLES.filter(v=>v.id!==corolla.id).slice(0,2);
const track={distanceMeters:402,cargoPayloadKg:0,inclineGradePercent:0};
const sim=new InteractiveRacePhysics([corolla],track,corolla.id,false);
for(let i=0;i<450;i++)sim.step(PHYSICS_STEP,{throttle:1,brake:0,steer:0});
const current=sim.getCar(corolla.id);
assert.ok(current.speed>10,`Corolla no acelera: ${current.speed}`);
assert.ok(Number.isFinite(current.x)&&Number.isFinite(current.z));
for(let i=0;i<40;i++)sim.step(PHYSICS_STEP,{throttle:1,brake:0,steer:0.2});
const xInitial=sim.getCar(corolla.id).x;
assert.ok(Math.abs(xInitial)>0.15,'Corolla no gira');
for(let i=0;i<120;i++)sim.step(PHYSICS_STEP,{throttle:0,brake:1,steer:0});
assert.ok(sim.getCar(corolla.id).speed<current.bestSpeed,'Corolla no frena');
const sim2=new InteractiveRacePhysics([corolla],track,corolla.id,false);
sim2.addHazard('barrier',0,25);
for(let i=0;i<500;i++)sim2.step(PHYSICS_STEP,{throttle:1,brake:0,steer:0});
assert.ok(sim2.cars[0].impacts>0,'No hay colisiones contra obstáculo');
for(let i=0;i<500;i++)sim2.step(PHYSICS_STEP,{throttle:0,brake:0,steer:0.5,reverse:1});
assert.ok(sim2.cars[0].z<25,'La reversa no libera al Corolla del obstáculo');
console.log('OK Corolla Cross: 171 HP, 203 Nm, dirección, aceleración, freno, choques, reversa y datos marcados como estimados.');
console.log({speedKmh:Math.round(current.speed*3.6),lateralMetres:Number(xInitial.toFixed(2)),collisions:sim2.cars[0].impacts});
