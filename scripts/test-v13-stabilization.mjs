import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { canStartCountdown, raceStartupMessage } from '../src/utils/raceStartupGate.ts';
const read = filename => readFileSync(new URL(`../${filename}`, import.meta.url), 'utf8');
const ready = { sceneRendered: true, loadedModels: 3, requiredModels: 3, modelError: false };
assert.equal(canStartCountdown(ready), true, 'Escena y tres GLBs listos');
assert.equal(canStartCountdown({ ...ready, sceneRendered: false }), false, 'Sin primer frame');
assert.equal(canStartCountdown({ ...ready, loadedModels: 2 }), false, 'GLB rival pendiente');
assert.equal(canStartCountdown({ ...ready, modelError: true }), false, 'Error no debe hacer largar');
assert.match(raceStartupMessage({ ...ready, loadedModels: 1 }), /Cargando/);
const race=read('src/components/Race3DPerspectiveView.tsx');
const viewer=read('src/components/Photographic360Viewer.tsx');
const sound=read('src/utils/soundEngine.ts');
const app=read('src/App.tsx');
assert.match(race, /const \[startRequested, setStartRequested\] = useState\(experience !== 'race'\)/, 'Desktop debe esperar');
assert.match(race, /completedModels \+= 1/, 'Cada GLB debe contar');
assert.match(race, /sceneDisposed = true/, 'No actualizar estado tras desmontar');
assert.match(race, /raceGateReady/, 'Gate conectado a la vista');
assert.match(race, /uiDeltaSeconds/, 'Atasco medido por tiempo');
assert.ok(!sound.includes('playFinishCheer'), 'Ovación eliminada');
assert.ok(!viewer.includes('for (let i = 1; i <= count; i++)'), 'No solicitar todos los frames');
assert.ok(!viewer.includes('autoPlay muted loop'), 'Giro manual');
assert.match(app, /V13/, 'Versión visible');
console.log('V13 PASS: inicio condicionado por modelos y frame, error controlado, atasco temporal, audio sin ovación, visor bajo demanda.');
